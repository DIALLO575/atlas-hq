import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync('packages/engines/mausbot/src/books-offline.mjs', 'utf8');
const output = '// Generated by scripts/generate-books-offline-cache.mjs. No application data.\n' + source;
if (process.argv.includes('--check')) {
  if (readFileSync('public/books-offline-cache.mjs', 'utf8') !== output) throw new Error('Regenerate books offline cache module');
} else writeFileSync('public/books-offline-cache.mjs', output);
